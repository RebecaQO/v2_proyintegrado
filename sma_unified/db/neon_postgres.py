def obtener_stats_consistencia() -> Dict[str, Any]:
    """Estadísticas rápidas del corpus normativo cargado y de los hallazgos emitidos."""
    try:
        conn = get_conn()
        cur = conn.cursor()
        cur.execute("SELECT COUNT(DISTINCT documento) FROM public.articulos_normativos")
        total_normas = cur.fetchone()[0]
        cur.execute("SELECT COUNT(*) FROM public.articulos_normativos WHERE estado = 'vigente'")
        total_articulos = cur.fetchone()[0]
        cur.execute(
            "SELECT tipo_relacion, COUNT(*) FROM normativa.analisis_consistencia GROUP BY tipo_relacion"
        )
        por_tipo = {r[0]: r[1] for r in cur.fetchall()}
        cur.close()
        return {"total_normas": total_normas, "total_articulos": total_articulos, "hallazgos_por_tipo": por_tipo}
    except Exception as e:
        logger.warning(f"No se pudieron obtener stats de consistencia normativa: {e}")
        return {"total_normas": 0, "total_articulos": 0, "hallazgos_por_tipo": {}}

