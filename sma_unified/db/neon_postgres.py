def buscar_articulos_normativa_similares(
    embedding: List[float], umbral: float = 0.55, top_k: int = 8
) -> List[Dict[str, Any]]:
    """
    Busca en normativa.articulos los artículos vigentes semánticamente más
    cercanos al embedding dado (similitud coseno vía pgvector), filtrando
    por el umbral mínimo de similitud.
    """
    try:
        conn = get_conn()
        cur = conn.cursor()
        literal = _embedding_a_literal_pgvector(embedding)
        cur.execute(
            """
            SELECT a.id, a.numero_articulo, a.texto, n.nombre AS norma,
                   1 - (a.embedding <=> %s::vector) AS similitud
            FROM normativa.articulos a
            JOIN normativa.normas n ON n.id = a.norma_id
            WHERE a.vigente = TRUE AND a.embedding IS NOT NULL
            ORDER BY a.embedding <=> %s::vector
            LIMIT %s
            """,
            (literal, literal, top_k),
        )
        filas = cur.fetchall()
        cur.close()
        resultado = [
            {"id": f[0], "numero_articulo": f[1], "texto": f[2], "norma": f[3], "similitud": float(f[4])}
            for f in filas
        ]
        return [r for r in resultado if r["similitud"] >= umbral]
    except Exception as e:
        try:
            get_conn().rollback()
        except Exception:
            pass
        logger.warning(f"⚠️  Búsqueda de consistencia normativa falló (¿corpus vacío?): {e}")
        return []


def guardar_analisis_consistencia(
    articulo_nuevo_texto: str,
    articulo_candidato_id: Optional[int],
    similitud: float,
    tipo_relacion: str,
    justificacion: str,
    sugerencia: str,
    sesion_id: Optional[str] = None,
    task_id_mongo: Optional[str] = None,
    id_proyecto: Optional[int] = None,
    modelo_llm: Optional[str] = None,
    nombre_archivo: Optional[str] = None,
    articulo_proyecto_numero: Optional[str] = None,
    articulo_candidato_documento: Optional[str] = None,
    articulo_candidato_numero: Optional[str] = None,
) -> Optional[int]:
    """
    Persiste un hallazgo (llamada de atención) del Agente de Consistencia
    Normativa. `nombre_archivo` guarda el PDF/documento enviado por el
    usuario que originó el hallazgo, y `articulo_candidato_documento` /
    `articulo_candidato_numero` identifican la norma vigente en conflicto
    tal como está en public.articulos_normativos (Código Penal, Código de
    Minería, cualquier ley cargada en "Base Legal").
    """
    try:
        conn = get_conn()
        cur = conn.cursor()
        cur.execute(
            """
            INSERT INTO normativa.analisis_consistencia
                (id_proyecto, sesion_id, task_id_mongo, nombre_archivo,
                 articulo_proyecto_numero, articulo_nuevo_texto,
                 articulo_candidato_id, articulo_candidato_documento,
                 articulo_candidato_numero, similitud, tipo_relacion,
                 justificacion, sugerencia, modelo_llm)
            VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s)
            RETURNING id
            """,
            (
                id_proyecto, sesion_id, task_id_mongo, nombre_archivo,
                articulo_proyecto_numero, articulo_nuevo_texto,
                articulo_candidato_id, articulo_candidato_documento,
                articulo_candidato_numero, round(float(similitud), 4), tipo_relacion,
                justificacion, sugerencia, modelo_llm,
            ),
        )
        id_analisis = cur.fetchone()[0]
        conn.commit()
        cur.close()
        return id_analisis
    except Exception as e:
        try:
            get_conn().rollback()
        except Exception:
            pass
        logger.warning(f"⚠️  No se pudo guardar el hallazgo de consistencia normativa: {e}")
        return None


