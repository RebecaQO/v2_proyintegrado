def buscar_articulos_constitucion_exacto(numero_articulo: str) -> Optional[Dict[str, Any]]:
    """Busca un artículo exacto por número en public.articulos_constitucion."""
    try:
        conn = get_conn()
        cur = conn.cursor()
        for col in ("contenido", "texto_articulo"):
            try:
                cur.execute(
                    f"""
                    SELECT
                        COALESCE(articulo_numero, '') AS numero,
                        COALESCE(articulo_titulo, '') AS titulo,
                        COALESCE({col}, '')            AS texto,
                        COALESCE(capitulo, '')         AS capitulo,
                        COALESCE(seccion, '')          AS seccion
                    FROM public.articulos_constitucion
                    WHERE articulo_numero ILIKE %s OR articulo_numero = %s
                    LIMIT 1
                    """,
                    (f"%{numero_articulo}%", numero_articulo),
                )
                row = cur.fetchone()
                if row:
                    cur.close()
                    return {
                        "numero": row[0],
                        "titulo": row[1],
                        "texto": row[2],
                        "capitulo": row[3],
                        "seccion": row[4],
                    }
            except Exception:
                try:
                    conn.rollback()
                except Exception:
                    pass
                continue
        cur.close()
        return None
    except Exception as e:
        logger.warning(f"Error buscando artículo exacto {numero_articulo}: {e}")
        return None


# ════════════════════════════════════════════════════════════════════════════
# AGENTE DE CONSISTENCIA NORMATIVA (corpus vigente + búsqueda semántica pgvector)
#   El corpus contra el que se coteja es public.articulos_normativos (la misma
#   tabla que llena la pantalla "Base Legal": Código Penal, Código de Minería,
#   leyes, decretos, resoluciones...), vía buscar_articulos_normativos_semantico().
#   normativa.normas / normativa.articulos quedan como esquema legado (lo usaba
#   una carga previa vía cargar_normativa.py) y ya no se escriben ni consultan
#   en el flujo activo del Agente de Consistencia.
#   normativa.analisis_consistencia sigue siendo la bitácora de hallazgos
#   (contradicción/repetición/vacío/complementario), ahora con nombre_archivo
#   y articulo_proyecto_numero para saber a qué PDF y qué artículo del
#   proyecto corresponde cada llamada de atención.
# ════════════════════════════════════════════════════════════════════════════

def _ensure_consistencia_tables(conn) -> None:
    """Crea el esquema `normativa` (extensión pgvector + tablas) si no existe."""
    ddl = f"""
    CREATE EXTENSION IF NOT EXISTS vector;
    CREATE SCHEMA IF NOT EXISTS normativa;

    CREATE TABLE IF NOT EXISTS normativa.normas (
        id                SERIAL PRIMARY KEY,
        nombre            TEXT NOT NULL,
        tipo_norma        VARCHAR(50),
        jerarquia         INTEGER,
        fuente_archivo    TEXT,
        creado_en         TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
        UNIQUE (nombre, fuente_archivo)
    );

    CREATE TABLE IF NOT EXISTS normativa.articulos (
        id                 SERIAL PRIMARY KEY,
        norma_id           INTEGER NOT NULL REFERENCES normativa.normas(id) ON DELETE CASCADE,
        numero_articulo    VARCHAR(30) NOT NULL,
        titulo_articulo    TEXT,
        texto              TEXT NOT NULL,
        parte              TEXT,
        titulo             TEXT,
        capitulo           TEXT,
        seccion            TEXT,
        vigente            BOOLEAN DEFAULT TRUE,
        embedding          vector({int(os.getenv("NVIDIA_EMBED_DIM", "2048"))}),
        creado_en          TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
        UNIQUE (norma_id, numero_articulo)
    );
    CREATE INDEX IF NOT EXISTS idx_normativa_articulos_vigente
        ON normativa.articulos(vigente);

    CREATE TABLE IF NOT EXISTS normativa.analisis_consistencia (
        id                          SERIAL PRIMARY KEY,
        id_proyecto                 INTEGER REFERENCES sistema.proyecto_ley(id_proyecto) ON DELETE SET NULL,
        sesion_id                   VARCHAR(36),
        task_id_mongo                VARCHAR(36),
        nombre_archivo               TEXT,
        articulo_proyecto_numero     TEXT,
        articulo_nuevo_texto         TEXT NOT NULL,
        articulo_candidato_id        BIGINT,
        articulo_candidato_documento TEXT,
        articulo_candidato_numero    TEXT,
        similitud                    NUMERIC(6,4),
        tipo_relacion                VARCHAR(20)
                                        CHECK (tipo_relacion IN
                                            ('contradiccion','repeticion','vacio_llenado',
                                             'complementario','sin_relacion')),
        justificacion                TEXT,
        sugerencia                   TEXT,
        modelo_llm                   VARCHAR(100),
        fecha_analisis                TIMESTAMP WITH TIME ZONE DEFAULT NOW()
    );
    CREATE INDEX IF NOT EXISTS idx_analisis_consistencia_proyecto
        ON normativa.analisis_consistencia(id_proyecto);
    CREATE INDEX IF NOT EXISTS idx_analisis_consistencia_sesion
        ON normativa.analisis_consistencia(sesion_id);
    CREATE INDEX IF NOT EXISTS idx_analisis_consistencia_tipo
        ON normativa.analisis_consistencia(tipo_relacion);

    ALTER TABLE normativa.analisis_consistencia
        ADD COLUMN IF NOT EXISTS nombre_archivo TEXT,
        ADD COLUMN IF NOT EXISTS articulo_proyecto_numero TEXT,
        ADD COLUMN IF NOT EXISTS articulo_candidato_documento TEXT,
        ADD COLUMN IF NOT EXISTS articulo_candidato_numero TEXT;

    CREATE INDEX IF NOT EXISTS idx_analisis_consistencia_archivo
        ON normativa.analisis_consistencia(nombre_archivo);
    """
    try:
        cur = conn.cursor()
        cur.execute(ddl)
        conn.commit()
        cur.close()
        logger.info("✅ Esquema normativa (pgvector) verificado/creado")
    except Exception as e:
        conn.rollback()
        logger.warning(
            f"⚠️  No se pudo crear el esquema normativa (¿pgvector no disponible en esta BD?): {e}"
        )
        return

    # ── Migración para bases ya existentes (creadas antes de este cambio):
    #    la tabla analisis_consistencia venía con articulo_candidato_id como
    #    FK a normativa.articulos. Los hallazgos ahora se resuelven contra
    #    public.articulos_normativos (otra tabla, otro espacio de ids), así
    #    que esa FK ya no aplica y hay que soltarla + agregar las columnas
    #    nuevas (nombre_archivo, articulo_proyecto_numero, documento/numero
    #    del candidato) si todavía no existen. Cada paso es best-effort y no
    #    interrumpe el arranque si algo falla. ──────────────────────────────
    try:
        cur = conn.cursor()
        cur.execute("""
            DO $$
            DECLARE
                fk_name TEXT;
            BEGIN
                SELECT conname INTO fk_name
                FROM pg_constraint
                WHERE conrelid = 'normativa.analisis_consistencia'::regclass
                  AND contype = 'f'
                  AND conname LIKE '%articulo_candidato_id%';
                IF fk_name IS NOT NULL THEN
                    EXECUTE format('ALTER TABLE normativa.analisis_consistencia DROP CONSTRAINT %I', fk_name);
                END IF;
            END $$;

            ALTER TABLE normativa.analisis_consistencia
                ADD COLUMN IF NOT EXISTS nombre_archivo TEXT,
                ADD COLUMN IF NOT EXISTS articulo_proyecto_numero TEXT,
                ADD COLUMN IF NOT EXISTS articulo_candidato_documento TEXT,
                ADD COLUMN IF NOT EXISTS articulo_candidato_numero TEXT;
        """)
        conn.commit()
        cur.close()
    except Exception as e:
        conn.rollback()
        logger.warning(f"⚠️  Migración de columnas nuevas en analisis_consistencia falló (no crítico): {e}")


def _embedding_a_literal_pgvector(embedding: List[float]) -> str:
    """Convierte una lista de floats al formato literal que espera pgvector: '[v1,v2,...]'."""
    return "[" + ",".join(f"{v:.8f}" for v in embedding) + "]"


