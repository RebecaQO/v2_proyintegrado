def guardar_proyecto_ley(
    sesion_id: str,
    texto_documento: str,
    nombre_archivo: Optional[str] = None,
    comision_data: Optional[Dict[str, Any]] = None,
    dictamen: Optional[Dict[str, Any]] = None,
    tipo_entrada: str = "Texto",
    drive_file_id: Optional[str] = None,
    drive_link: Optional[str] = None,
) -> Optional[int]:
    """
    Inserta o actualiza un proyecto de ley en sistema.proyecto_ley con el esquema exacto:
    (id_proyecto, numero_expediente, id_usuario_presentante, titulo, resumen, texto_completo,
     archivo_pdf, fecha_ingreso, id_estado_actual, id_comision_actual, prioridad,
     numero_ley_asignado, fecha_publicacion, fecha_vigencia, activo, observaciones_generales)
    """
    try:
        conn = get_conn()
        cur = conn.cursor()

        comision_data = comision_data or {}
        dictamen = dictamen or {}

        prioridad_map = {
            "urgente": "Urgente", "alta": "Alta",
            "normal": "Media", "media": "Media",
            "baja": "Baja",
        }
        prioridad = prioridad_map.get(
            str(comision_data.get("prioridad", "Media")).lower(), "Media"
        )

        titulo = str(comision_data.get("resumen", nombre_archivo or "Proyecto de Ley")).split("\n")[0][:400]
        resumen = str(comision_data.get("resumen", ""))[:2000]
        comision_sugerida = str(comision_data.get("comision_principal", ""))
        
        # Buscar id_comision si ya se tiene la sugerida
        id_comision = None
        if comision_sugerida:
            cur.execute(
                """
                SELECT id_comision FROM sistema.comision 
                WHERE LOWER(nombre_comision) = LOWER(%s)
                   OR LOWER(nombre_corto) = LOWER(%s)
                   OR LOWER(codigo_comision) = LOWER(%s)
                   OR %s ILIKE CONCAT('%%', nombre_corto, '%%')
                LIMIT 1
                """,
                (comision_sugerida, comision_sugerida, comision_sugerida, comision_sugerida)
            )
            c_row = cur.fetchone()
            if c_row:
                id_comision = c_row[0]

        # Generar número de expediente correlativo si es nuevo
        ano_actual = datetime.now().year
        num_exp = f"PL-{ano_actual}-{sesion_id[:6].upper()}"

        # Buscar si ya existe un proyecto con este sesion_id
        cur.execute(
            "SELECT id_proyecto FROM sistema.proyecto_ley WHERE observaciones_generales LIKE %s LIMIT 1",
            (f"%sesion:{sesion_id}%",),
        )
        existing = cur.fetchone()

        if existing:
            id_proyecto = existing[0]
            cur.execute(
                """
                UPDATE sistema.proyecto_ley SET
                    titulo = %s,
                    resumen = %s,
                    id_comision_actual = COALESCE(%s, id_comision_actual),
                    prioridad = %s,
                    drive_file_id = COALESCE(%s, drive_file_id),
                    drive_link = COALESCE(%s, drive_link)
                WHERE id_proyecto = %s
                """,
                (titulo, resumen, id_comision, prioridad, drive_file_id, drive_link, id_proyecto),
            )
        else:
            cur.execute(
                """
                INSERT INTO sistema.proyecto_ley (
                    numero_expediente, id_usuario_presentante, titulo, resumen,
                    texto_completo, archivo_pdf, fecha_ingreso, id_estado_actual,
                    id_comision_actual, prioridad, activo, observaciones_generales,
                    drive_file_id, drive_link
                ) VALUES (
                    %s, 1, %s, %s,
                    %s, %s, NOW(), 1,
                    %s, %s, TRUE, %s,
                    %s, %s
                )
                RETURNING id_proyecto
                """,
                (
                    num_exp,
                    titulo,
                    resumen,
                    texto_documento,
                    nombre_archivo or "",
                    id_comision,
                    prioridad,
                    f"sesion:{sesion_id}",
                    drive_file_id,
                    drive_link,
                ),
            )
            row = cur.fetchone()
            id_proyecto = row[0] if row else None

        conn.commit()
        cur.close()
        logger.info(f"✅ proyecto_ley guardado en Neon → id: {id_proyecto} (Exp: {num_exp})")
        return id_proyecto
    except Exception as e:
        try:
            get_conn().rollback()
        except Exception:
            pass
        logger.warning(f"⚠️  No se pudo guardar proyecto_ley en Neon: {e}")
        return None


def asignar_comision_a_proyecto(
    id_proyecto: int,
    nombre_comision: str,
    observaciones: Optional[str] = None,
    valido_constitucional: Optional[bool] = None,
) -> Optional[int]:
    """
    Asigna id_comision_actual y id_estado_actual a un proyecto_ley
    buscando el id_comision en sistema.comision.
    """
    try:
        conn = get_conn()
        cur = conn.cursor()

        cur.execute(
            """
            SELECT id_comision, nombre_comision FROM sistema.comision 
            WHERE LOWER(nombre_comision) = LOWER(%s)
               OR LOWER(nombre_corto) = LOWER(%s)
               OR LOWER(codigo_comision) = LOWER(%s)
               OR %s ILIKE CONCAT('%%', nombre_corto, '%%')
               OR %s ILIKE CONCAT('%%', nombre_comision, '%%')
            LIMIT 1
            """,
            (nombre_comision, nombre_comision, nombre_comision, nombre_comision, nombre_comision)
        )
        row = cur.fetchone()
        id_comision = row[0] if row else None
        nombre_oficial = row[1] if row else nombre_comision

        # id_estado_actual: 2 = Derivado a Comisión, 3 = Con Observación Constitucional
        id_estado = 3 if valido_constitucional is False else 2

        obs_texto = f"\n[Comisión Asignada]: {nombre_oficial}"
        if observaciones:
            obs_texto += f"\n[Detalle]: {observaciones}"

        cur.execute(
            """
            UPDATE sistema.proyecto_ley SET
                id_comision_actual = %s,
                id_estado_actual = %s,
                observaciones_generales = CONCAT(COALESCE(observaciones_generales, ''), %s)
            WHERE id_proyecto = %s
            """,
            (id_comision, id_estado, obs_texto, id_proyecto)
        )
        conn.commit()
        cur.close()
        logger.info(f"✅ Comisión '{nombre_oficial}' (id_comision={id_comision}) asignada al proyecto #{id_proyecto}")
        return id_comision
    except Exception as e:
        try:
            get_conn().rollback()
        except Exception:
            pass
        logger.warning(f"No se pudo asignar comisión al proyecto #{id_proyecto}: {e}")
        return None


