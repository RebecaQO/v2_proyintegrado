def guardar_observacion_constitucional(
    sesion_id: str,
    dictamen: Dict[str, Any],
    id_proyecto: Optional[int] = None,
    task_id_mongo: Optional[str] = None,
    modelo_llm: str = "nvidia/nemotron-3-nano-omni-30b-a3b-reasoning",
    duracion_ms: int = 0,
    articulos_consultados: Optional[List] = None,
) -> Optional[int]:
    """Guarda el dictamen del agente verificador constitucional."""
    try:
        from psycopg2.extras import Json
        conn = get_conn()
        cur = conn.cursor()

        valido = bool(dictamen.get("valido", True))
        confianza = float(dictamen.get("confianza", 0)) if dictamen.get("confianza") is not None else None
        severidad = str(dictamen.get("severidad_maxima", "ninguna")).lower()
        if severidad not in ("ninguna", "leve", "grave", "bloqueante"):
            severidad = "ninguna"

        contradicciones = dictamen.get("contradicciones", [])
        analisis = dictamen.get("analisis_articulos", [])
        # Usar el parámetro explícito si viene, si no tomar del dictamen
        consultados = articulos_consultados if articulos_consultados is not None else dictamen.get("articulos_consultados", [])
        fundamentacion = dictamen.get("fundamentacion_general", "")
        num_contradicciones = len(contradicciones) if isinstance(contradicciones, list) else 0

        cur.execute(
            """
            INSERT INTO sistema.observaciones_constitucionales (
                id_proyecto, sesion_id, task_id_mongo,
                valido, confianza, severidad_maxima, num_contradicciones,
                fundamentacion, contradicciones, analisis_articulos,
                articulos_consultados, modelo_llm, duracion_ms,
                fecha_analisis, estado_dictamen
            ) VALUES (
                %s, %s, %s,
                %s, %s, %s, %s,
                %s, %s, %s,
                %s, %s, %s,
                NOW(), 'emitido'
            )
            RETURNING id_observacion
            """,
            (
                id_proyecto,
                sesion_id,
                task_id_mongo,
                valido,
                confianza,
                severidad,
                num_contradicciones,
                fundamentacion,
                Json(contradicciones),
                Json(analisis),
                Json(consultados),
                modelo_llm,
                duracion_ms,
            ),
        )
        row = cur.fetchone()
        conn.commit()
        cur.close()
        id_obs = row[0] if row else None
        logger.info(f"✅ Observación constitucional guardada → id: {id_obs} (válido={valido}, severidad={severidad})")
        return id_obs
    except Exception as e:
        try:
            get_conn().rollback()
        except Exception:
            pass
        logger.warning(f"⚠️  No se pudo guardar observacion_constitucional en Neon: {e}")
        return None


