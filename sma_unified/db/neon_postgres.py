def obtener_stats_constitucionales() -> Dict[str, Any]:
    """KPIs agregados de auditoría constitucional."""
    try:
        conn = get_conn()
        cur = conn.cursor()
        cur.execute("""
            SELECT
                COUNT(*) as total,
                COUNT(*) FILTER (WHERE valido = TRUE) as conformes,
                COUNT(*) FILTER (WHERE valido = FALSE) as con_contradicciones,
                COUNT(*) FILTER (WHERE severidad_maxima = 'bloqueante') as bloqueantes,
                COUNT(*) FILTER (WHERE severidad_maxima = 'grave') as graves,
                AVG(confianza) as promedio_confianza,
                SUM(num_contradicciones) as total_contradicciones
            FROM sistema.observaciones_constitucionales
        """)
        row = cur.fetchone()
        cur.close()
        if row:
            return {
                "total": row[0] or 0,
                "conformes": row[1] or 0,
                "con_contradicciones": row[2] or 0,
                "bloqueantes": row[3] or 0,
                "graves": row[4] or 0,
                "promedio_confianza": round(float(row[5] or 0), 1),
                "total_contradicciones": row[6] or 0,
            }
        return {"total": 0, "conformes": 0, "con_contradicciones": 0, "bloqueantes": 0, "graves": 0, "promedio_confianza": 0.0, "total_contradicciones": 0}
    except Exception as e:
        logger.warning(f"No se pudieron obtener stats constitucionales: {e}")
        return {"total": 0, "conformes": 0, "con_contradicciones": 0, "bloqueantes": 0, "graves": 0, "promedio_confianza": 0.0, "total_contradicciones": 0}


def obtener_ultimas_observaciones(limit: int = 10) -> List[Dict[str, Any]]:
    """Últimas N observaciones con datos del proyecto."""
    try:
        import psycopg2.extras
        conn = get_conn()
        cur = conn.cursor(cursor_factory=psycopg2.extras.RealDictCursor)
        cur.execute(
            """
            SELECT
                o.id_observacion,
                o.id_proyecto,
                o.sesion_id,
                o.valido,
                o.confianza,
                o.severidad_maxima,
                o.num_contradicciones,
                o.fundamentacion,
                o.fecha_analisis,
                o.estado_dictamen,
                p.titulo as titulo_proyecto,
                p.numero_expediente
            FROM sistema.observaciones_constitucionales o
            LEFT JOIN sistema.proyecto_ley p ON o.id_proyecto = p.id_proyecto
            ORDER BY o.fecha_analisis DESC
            LIMIT %s
            """,
            (limit,),
        )
        rows = [dict(r) for r in cur.fetchall()]
        cur.close()
        for r in rows:
            if isinstance(r.get("fecha_analisis"), datetime):
                r["fecha_analisis"] = r["fecha_analisis"].strftime("%Y-%m-%d %H:%M:%S")
        return rows
    except Exception as e:
        logger.warning(f"No se pudieron obtener observaciones: {e}")
        return []


