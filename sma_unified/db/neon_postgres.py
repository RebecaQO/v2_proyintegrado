# ── Lazy singleton de conexión ────────────────────────────────────────────────
_conn = None
_tables_ensured = False
# Compartido por los análisis de Constitucionalidad y Consistencia que corren
# en paralelo y consultan la conexión singleton psycopg2.
ANALISIS_NEON_LOCK = Lock()


def get_conn():
    """Retorna una conexión psycopg2 a Neon PostgreSQL (singleton)."""
    global _conn, _tables_ensured
    try:
        if _conn is not None and not _conn.closed:
            # Test that connection is alive
            with _conn.cursor() as cur:
                cur.execute("SELECT 1")
            return _conn
    except Exception:
        _conn = None

    try:
        import psycopg2

        url = os.getenv("NEON_DATABASE_URL", "")
        if not url:
            raise ValueError("NEON_DATABASE_URL no configurada en .env")

        _conn = psycopg2.connect(url, connect_timeout=10)
        _conn.autocommit = True
        with _conn.cursor() as cur:
            cur.execute("SET search_path TO sistema, public;")
        logger.info("✅ PostgreSQL Neon conectado (search_path: sistema, public)")
        
        if not _tables_ensured:
            _tables_ensured = True
            try:
                _ensure_observaciones_table(_conn)
                _ensure_consistencia_tables(_conn)
                _ensure_articulos_normativos_table(_conn)
                _ensure_normativas_catalogadas_table(_conn)
                _ensure_usuarios_table(_conn)
                _ensure_correcciones_table(_conn)
                _ensure_legislativo_14_agentes_tables(_conn)
            except Exception as em:
                logger.warning(f"Aviso durante ensure_tables Neon: {em}")
        return _conn
    except Exception as e:
        logger.error(f"❌ No se pudo conectar a PostgreSQL Neon: {e}")
        raise


def ping_neon() -> bool:
    """Retorna True si Neon PostgreSQL responde correctamente."""
    try:
        conn = get_conn()
        with conn.cursor() as cur:
            cur.execute("SELECT 1")
        return True
    except Exception:
        return False



